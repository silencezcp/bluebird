#!/usr/bin/env python
"""Write the icon assets and the Windows version resource for the build.

    D:\\DSH_Workspaces\\Ftp\\python.exe tools\\make_icon.py

Produces, in ``packaging/``:

* ``bluebird.png``          256 px preview / store icon
* ``bluebird.ico``          multi-resolution icon used by the executable
* ``version_info.txt``      PyInstaller version resource (author: silence)

The artwork lives in :mod:`ftpclient.appicon` and is drawn with QPainter, so it
can be regenerated at any time instead of shipping a binary that nobody can
edit.
"""

from __future__ import annotations

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

# NOTE: the offline platform plugin ships no fonts at all (QFontDatabase is
# empty).  The bird does not draw text, so it renders correctly either way,
# but the real platform is still preferred: it is what the finished icon is
# actually seen through, and offscreen stays a fallback for headless machines.
if not os.environ.get("QT_QPA_PLATFORM"):
    os.environ["QT_QPA_PLATFORM"] = "windows"

from PyQt5.QtGui import QFontDatabase  # noqa: E402
from PyQt5.QtWidgets import QApplication  # noqa: E402

app = QApplication(sys.argv[:1])

if not QFontDatabase().families():
    print("  ! no fonts on platform %r: retrying at a larger scale is not"
          " possible, the lettering would be missing" % app.platformName())
    for candidate in ("windows", "minimal"):
        os.environ["QT_QPA_PLATFORM"] = candidate
        QApplication.removePostedEvents(None)
        break

from ftpclient import (__appname__, __author__, __author_email__,  # noqa: E402
                       __copyright__, __version__)
from ftpclient import appicon  # noqa: E402

PACKAGING = os.path.join(ROOT, "packaging")

VERSION_INFO = """\
# UTF-8
# PyInstaller version resource for {appname}.  Generated by tools/make_icon.py
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '080404b0',
        [StringStruct('CompanyName', '{author}'),
         StringStruct('FileDescription', '{appname} - FTP / FTPS / SFTP client'),
         StringStruct('FileVersion', '{version}'),
         StringStruct('InternalName', '{appname}'),
         StringStruct('LegalCopyright', '{copyright}'),
         StringStruct('OriginalFilename', 'BlueBird.exe'),
         StringStruct('ProductName', '{appname}'),
         StringStruct('ProductVersion', '{version}'),
         StringStruct('Author', '{author}'),
         StringStruct('Comments', 'Author: {author} <{email}>')])
    ]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
"""


def version_tuple(version: str) -> str:
    parts = []
    for chunk in version.split(".")[:4]:
        try:
            parts.append(int(chunk))
        except ValueError:
            parts.append(0)
    while len(parts) < 4:
        parts.append(0)
    return "(%s)" % ", ".join(str(part) for part in parts)


def main() -> int:
    if not os.path.isdir(PACKAGING):
        os.makedirs(PACKAGING)

    families = len(QFontDatabase().families())
    print("  platform: %s | font families: %d" % (app.platformName(), families))
    if not families:
        # the icon draws no text, so a fontless platform still produces the
        # right picture; only the manual's typography would suffer
        print("  ! WARNING: no fonts are available.  The bird draws no text, so")
        print("    the icon is unaffected; run this on a normal desktop session")
        print("    if you also want the manual to render properly.")

    written = appicon.write_assets(PACKAGING)
    for path in written:
        print("  wrote %s (%d bytes)" % (path, os.path.getsize(path)))
    if not written:
        print("  ! no icon could be rendered")
        return 1

    # The user manual embeds a copy of the icon.  Refresh it here so the manual
    # and the executable can never show different artwork - they were allowed
    # to drift once, and the packaged manual ended up with the old drawing.
    import shutil
    manual_copy = os.path.join(ROOT, "docs", "screenshots", "21-app-icon.png")
    source = os.path.join(PACKAGING, "bluebird.png")
    if os.path.isfile(source):
        try:
            if not os.path.isdir(os.path.dirname(manual_copy)):
                os.makedirs(os.path.dirname(manual_copy))
            shutil.copyfile(source, manual_copy)
            print("  refreshed %s (%d bytes)"
                  % (manual_copy, os.path.getsize(manual_copy)))
        except OSError as exc:
            print("  ! could not refresh the manual's icon copy: %s" % exc)

    target = os.path.join(PACKAGING, "version_info.txt")
    payload = VERSION_INFO.format(
        appname=__appname__, author=__author__, email=__author_email__,
        version=__version__, copyright=__copyright__,
        nums=version_tuple(__version__))
    with io.open(target, "w", encoding="utf-8", newline="\r\n") as handle:
        handle.write(payload)
    print("  wrote %s (%d bytes)" % (target, os.path.getsize(target)))
    print("  author: %s <%s>" % (__author__, __author_email__))
    return 0


if __name__ == "__main__":
    sys.exit(main())
